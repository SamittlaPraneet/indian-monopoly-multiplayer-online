export default function Token({
  family,
  colour = "#65b9a5",
  variant = "icon",
  size = 36,
}: {
  family: number;
  colour?: string;
  variant?: string;
  size?: number;
}) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 64 50"
      aria-label={tokens[family]}
      role="img"
      className={variant === "icon" ? "token" : "token shaded"}
    >
      <polygon
        points={outlines[family].map((p) => p.join(",")).join(" ")}
        fill={colour}
        stroke="currentColor"
        strokeWidth="2"
        strokeLinejoin="round"
      />
      {family < 9 && ![5, 8].includes(family) && (
        <>
          <circle cx="16" cy="36" r="5" fill="#192b31" />
          <circle cx="49" cy="36" r="5" fill="#192b31" />
        </>
      )}
      {family === 5 && (
        <>
          <circle
            cx="11"
            cy="33"
            r="10"
            fill="none"
            stroke={colour}
            strokeWidth="3"
          />
          <circle
            cx="51"
            cy="33"
            r="10"
            fill="none"
            stroke={colour}
            strokeWidth="3"
          />
        </>
      )}
      {family === 19 && (
        <>
          <circle cx="28" cy="9" r="2" fill="white" />
          <circle cx="35" cy="9" r="2" fill="white" />
        </>
      )}
    </svg>
  );
}
